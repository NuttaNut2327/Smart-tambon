def paragraph(text="", first=False, italic=False, color="000000"):
    p = doc.add_paragraph()
    if first:
        p.paragraph_format.first_line_indent = Cm(0.75)
    r = p.add_run(text); set_font(r, size=15, italic=italic, color=color)
    return p

def numbered(items):
    for i, item in enumerate(items, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.85)
        p.paragraph_format.first_line_indent = Cm(-0.65)
        r = p.add_run(f"{i}.  {item}"); set_font(r, size=15)

def bullets(items):
    for item in items:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.85)
        p.paragraph_format.first_line_indent = Cm(-0.5)
        r = p.add_run(f"•  {item}"); set_font(r, size=15)

def caption(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(3); p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text); set_font(r, size=13, color="666666", italic=True)

def add_image(path, caption_text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(path), width=Cm(17.0))
    caption(caption_text)

def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd"); shd.set(qn("w:fill"), fill); tcPr.append(shd)

def border_table(table):
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}"); e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4"); e.set(qn("w:color"), "D9D9D9"); borders.append(e)
    tblPr.append(borders)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        t.rows[0].cells[j].text = h; shade(t.rows[0].cells[j], "244A3A")
    for i, row in enumerate(rows, 1):
        cells = t.add_row().cells
        for j, value in enumerate(row):
            cells[j].text = value
            shade(cells[j], "EFF4F1" if i % 2 == 0 else "FFFFFF")
    for i, row in enumerate(t.rows):
        for j, cell in enumerate(row.cells):
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tcPr = cell._tc.get_or_add_tcPr(); tcMar = OxmlElement("w:tcMar")
            for side in ("top", "start", "bottom", "end"):
                m = OxmlElement(f"w:{side}"); m.set(qn("w:w"), "100"); m.set(qn("w:type"), "dxa"); tcMar.append(m)
            tcPr.append(tcMar)
            for p in cell.paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER if j == 0 else WD_ALIGN_PARAGRAPH.LEFT
                for r in p.runs:
                    set_font(r, size=13, bold=(i == 0), color="FFFFFF" if i == 0 else "000000")
    border_table(t)
    return t

