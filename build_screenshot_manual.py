def set_font(run, size=16, bold=None, color="000000", italic=False):
    name = "TH Sarabun New"
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    for k in ("ascii", "hAnsi", "eastAsia"):
        rpr.rFonts.set(qn(f"w:{k}"), name)
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    run.font.italic = italic
    run.font.color.rgb = RGBColor.from_string(color)

