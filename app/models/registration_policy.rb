# Subscription terms and PDPA notice shown in the อบต. registration wizard. Texts can be overridden by the system
# admin (SystemSetting#registration_terms / #registration_pdpa); the version is a fingerprint of the exact text,
# so every acceptance records which wording the applicant agreed to.
# NOTE: the defaults below are drafts for development and must be reviewed by a legal advisor before production use.
module RegistrationPolicy
  DEFAULT_TERMS = <<~TEXT.freeze
    ข้อตกลงการใช้บริการ (Subscription Terms)

    1. ผู้ให้บริการ: ระบบนี้ให้บริการแก่องค์กรปกครองส่วนท้องถิ่น (อปท.) เพื่อบริหารจัดการข้อมูลพื้นที่ เหตุการณ์ ภัยพิบัติ และการประชาสัมพันธ์
    2. คุณสมบัติผู้สมัคร: ผู้สมัครต้องเป็นเจ้าหน้าที่หรือผู้ได้รับมอบหมายจาก อปท. ที่ระบุ และยืนยันว่าข้อมูลที่กรอกเป็นความจริง ผู้ดูแลระบบอาจขอเอกสารยืนยันเพิ่มเติมก่อนอนุมัติ
    3. บัญชีผู้ใช้: ผู้สมัครเป็นผู้ดูแลบัญชีของหน่วยงาน มีหน้าที่เก็บรักษารหัสผ่านเป็นความลับ กำหนดสิทธิ์ผู้ใช้ภายในหน่วยงานอย่างเหมาะสม และแจ้งผู้ดูแลระบบทันทีหากพบการใช้งานโดยไม่ได้รับอนุญาต
    4. การใช้งานที่เหมาะสม: ใช้ระบบเพื่อภารกิจของหน่วยงานเท่านั้น ห้ามนำเข้าข้อมูลที่ผิดกฎหมาย ละเมิดสิทธิผู้อื่น หรือพยายามเข้าถึงข้อมูลของหน่วยงานอื่น
    5. ข้อมูลของหน่วยงาน: ข้อมูลที่หน่วยงานนำเข้าเป็นของหน่วยงาน ผู้ให้บริการประมวลผลข้อมูลตามคำสั่งของหน่วยงานและตามประกาศความเป็นส่วนตัว
    6. บริการภายนอก: บางฟังก์ชันเชื่อมต่อบริการภายนอก (เช่น แผนที่ SMS AI สร้างเสียง และโซเชียลมีเดีย) ซึ่งอยู่ภายใต้เงื่อนไขของผู้ให้บริการนั้น
    7. ความพร้อมให้บริการ: ผู้ให้บริการพยายามให้ระบบพร้อมใช้งานตลอดเวลา แต่อาจมีการปิดปรับปรุงหรือขัดข้องได้ ระบบไม่ใช่ช่องทางแจ้งเหตุฉุกเฉินแทนหมายเลข 191 / 199 / 1669
    8. การระงับบัญชี: ผู้ให้บริการอาจระงับหรือยกเลิกบัญชีที่ละเมิดข้อตกลงนี้ หรือเมื่อหน่วยงานแจ้งยกเลิก
    9. การเปลี่ยนแปลงข้อตกลง: ผู้ให้บริการอาจปรับปรุงข้อตกลงนี้ และจะแจ้งให้ทราบผ่านระบบ
  TEXT

  DEFAULT_PDPA = <<~TEXT.freeze
    ประกาศความเป็นส่วนตัวและการขอความยินยอม (PDPA)

    ตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562
    1. ข้อมูลที่เก็บ: ชื่อ-นามสกุล ตำแหน่ง อีเมล เบอร์โทรศัพท์ ชื่อผู้ใช้ ข้อมูลการเข้าใช้งาน (เวลา และหมายเลข IP) และบันทึกการยอมรับข้อตกลง
    2. วัตถุประสงค์: ยืนยันตัวตนและสิทธิ์ของผู้สมัคร สร้างและดูแลบัญชีผู้ใช้ ติดต่อเรื่องการใช้บริการ แจ้งเตือนเหตุการณ์ และรักษาความปลอดภัยของระบบ
    3. ฐานทางกฎหมาย: การปฏิบัติตามสัญญาการใช้บริการ ประโยชน์โดยชอบด้วยกฎหมายในการรักษาความปลอดภัย และความยินยอมของท่านสำหรับการติดต่อประชาสัมพันธ์ (ถ้าเลือก)
    4. การเปิดเผยข้อมูล: เปิดเผยเฉพาะผู้ดูแลระบบและผู้ให้บริการที่จำเป็น เช่น ผู้ให้บริการส่ง SMS/อีเมล ภายใต้ข้อตกลงรักษาความลับ ไม่ขายข้อมูลให้บุคคลภายนอก
    5. ระยะเวลาเก็บรักษา: ตลอดระยะเวลาที่มีบัญชี และไม่เกิน 2 ปีหลังปิดบัญชี เว้นแต่กฎหมายกำหนดให้เก็บนานกว่า คำขอที่ไม่ได้รับอนุมัติจะถูกลบภายใน 90 วัน
    6. สิทธิของเจ้าของข้อมูล: ขอเข้าถึง แก้ไข ลบ ระงับ คัดค้าน หรือโอนย้ายข้อมูล และถอนความยินยอมได้ตลอดเวลา โดยติดต่อผู้ดูแลระบบ
    7. ความปลอดภัย: รหัสผ่านถูกเข้ารหัสแบบทางเดียว ข้อมูลรับส่งผ่านการเข้ารหัส และจำกัดการเข้าถึงตามสิทธิ์
    8. ติดต่อ: ผู้ควบคุมข้อมูลส่วนบุคคลคือผู้ให้บริการระบบ ติดต่อได้ตามช่องทางที่แสดงบนหน้าเว็บไซต์
  TEXT

  def self.terms = SystemSetting.current.try(:registration_terms).presence || DEFAULT_TERMS
  def self.pdpa = SystemSetting.current.try(:registration_pdpa).presence || DEFAULT_PDPA
  def self.version(text) = Digest::SHA256.hexdigest(text.to_s)[0, 12]
  def self.terms_version = version(terms)
  def self.pdpa_version = version(pdpa)
end
